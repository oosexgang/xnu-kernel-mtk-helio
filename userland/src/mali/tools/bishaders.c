/*
 * bishaders: shaders_v7.h, the library's programs as compiler.c compiles them on this machine with Mesa's Bifrost
 * compiler for the phone's Mali-G52 r1 (0x7402): the same code the driver runs on the phone (mali-probe stage
 * compiler holds the two word for word). Built and run by tools/mk-shaders.sh against a host build of Mesa 25.0.7.
 */
#include <execinfo.h>
#include <signal.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

#include "../compiler.h"

#define GPU_ID 0x7402u

static FILE *out;

static void
fatal(int sig)
{
	void *frames[48];
	int n = backtrace(frames, 48);

	fprintf(stderr, "bishaders: signal %d\n", sig);
	backtrace_symbols_fd(frames, n, 2);
	_exit(70);
}

static void
words(const char *prefix, const char *name, const uint32_t *w, unsigned n)
{
	fprintf(out, "static const uint32_t hm_%s_%s[%u] = {", prefix, name, n);
	for (unsigned i = 0; i < n; i++) {
		fprintf(out, "%s0x%08x,", i % 8 ? " " : "\n\t", w[i]);
	}
	fprintf(out, "\n};\n");
}

static void
pushes(const char *prefix, const char *name, const struct hm_push_word *p, unsigned n)
{
	fprintf(out, "static const struct hm_push_word hm_%s_%s[%u] = {", prefix, name, n ? n : 1);
	for (unsigned i = 0; i < n; i++) {
		fprintf(out, "%s{ %u, %u },", i % 8 ? " " : "\n\t", p[i].ubo, p[i].offset);
	}
	fprintf(out, "%s\n};\n", n ? "" : " { 0, 0 }");
}

static void
varyings(const char *prefix, const char *name, const struct hm_varying *v, unsigned n)
{
	fprintf(out, "static const struct hm_varying hm_%s_%s[%u] = {\n", prefix, name, n ? n : 1);
	for (unsigned i = 0; i < n; i++) {
		fprintf(out, "\t{ %u, 0x%08x, %u },\n", v[i].location, v[i].format, v[i].size);
	}
	fprintf(out, "%s};\n", n ? "" : "\t{ 0, 0, 0 },\n");
}

static void
program(const char *name)
{
	struct hm_program p;
	char why[200];

	if (hm_compile_program(name, GPU_ID, &p, why, sizeof(why)) != 0) {
		fprintf(stderr, "bishaders: %s\n", why);
		_exit(1);
	}
	fprintf(out, "\n/* --- %s: vertex shader %u bytes, %u work registers; fragment shader %u bytes, %u work registers --- */\n",
	    name, p.vs_size, p.vs_work_registers, p.fs_size, p.fs_work_registers);
	words(name, "vs_code", p.vs_code, p.vs_size / 4);
	words(name, "fs_code", p.fs_code, p.fs_size / 4);
	words(name, "vs_rsd", p.vs_rsd, 16);
	words(name, "fs_rsd", p.fs_rsd, 16);
	words(name, "fs_rsd_depth", p.fs_rsd_depth, 16);
	words(name, "fs_rsd_blended", p.fs_rsd_blended, 16);
	words(name, "blend_off", p.blend_off, 4);
	words(name, "blend_over", p.blend_over, 4);
	words(name, "blend_off_bgra", p.blend_off_bgra, 4);
	words(name, "blend_over_bgra", p.blend_over_bgra, 4);
	pushes(name, "vs_push", p.vs_push, p.vs_push_count);
	pushes(name, "fs_push", p.fs_push, p.fs_push_count);
	varyings(name, "vs_out", p.vs_out, p.vs_out_count);
	varyings(name, "fs_in", p.fs_in, p.fs_in_count);
	words(name, "attribute_formats", p.attribute_formats, p.attribute_count);
	words(name, "attribute_sizes", p.attribute_sizes, p.attribute_count);
	fprintf(out, "static const struct hm_program hm_%s = {\n\t\"%s\",\n"
	    "\thm_%s_vs_code, %u, hm_%s_fs_code, %u,\n"
	    "\thm_%s_vs_rsd, hm_%s_fs_rsd, hm_%s_fs_rsd_blended, hm_%s_blend_off, hm_%s_blend_over,\n"
	    "\thm_%s_vs_push, %u, hm_%s_fs_push, %u,\n\thm_%s_vs_out, %u, hm_%s_fs_in, %u,\n"
	    "\thm_%s_attribute_formats, hm_%s_attribute_sizes, %u, %u, %u, %u,\n\thm_%s_fs_rsd_depth, %u, %u, hm_%s_blend_off_bgra, hm_%s_blend_over_bgra,\n};\n",
	    name, name, name, p.vs_size, name, p.fs_size, name, name, name, name, name, name, p.vs_push_count, name,
	    p.fs_push_count, name, p.vs_out_count, name, p.fs_in_count, name, name, p.attribute_count, p.texture_count,
	    p.sampler_count, p.can_blend, name, p.vs_work_registers, p.fs_work_registers, name, name);
	hm_program_free(&p);
}

int
main(int argc, char **argv)
{
	const char *path = argc > 1 ? argv[1] : "shaders_v7.h";
	struct hm_kernel k;
	char why[200];

	for (int sig = 1; sig < 32; sig++) {
		if (sig == SIGABRT || sig == SIGSEGV || sig == SIGBUS || sig == SIGILL || sig == SIGTRAP || sig == SIGFPE) {
			signal(sig, fatal);
		}
	}
	hm_compile_init();
	out = fopen(path, "w");
	if (out == NULL) {
		perror(path);
		return 1;
	}
	fprintf(out, "/*\n * Generated by tools/bishaders.c (tools/mk-shaders.sh): the library's programs as compiler.c compiles "
	    "them with Mesa 25.0.7's\n * Bifrost compiler for the Mali-G52 r1 (0x%x). Do not edit.\n */\n#pragma once\n"
	    "#include \"program.h\"\n", GPU_ID);
	program("tri");
	program("color");
	program("tex");
	program("inst");
	for (const char **name = (const char *[]){ "fill", "share", "copy", "copy2d", NULL }; *name; name++) {
		if (hm_compile_kernel(*name, GPU_ID, &k, why, sizeof(why)) != 0) {
			fprintf(stderr, "bishaders: %s\n", why);
			return 1;
		}
		fprintf(out, "\n/* --- %s: compute shader %u bytes, %u work registers, %u bytes of threadgroup memory --- */\n",
		    *name, k.size, k.work_registers, k.wls_size);
		words(*name, "cs_code", k.code, k.size / 4);
		words(*name, "cs_rsd", k.rsd, 16);
		pushes(*name, "cs_push", k.push, k.push_count);
		fprintf(out, "static const struct hm_kernel hm_%s = { \"%s\", hm_%s_cs_code, %u, hm_%s_cs_rsd, hm_%s_cs_push, "
		    "%u, { %u, %u, %u }, %u, %u, %u, %u };\n", *name, *name, *name, k.size, *name, *name, k.push_count, k.local[0],
		    k.local[1], k.local[2], k.tls_size, k.work_registers, k.ubo_count, k.wls_size);
		hm_kernel_free(&k);
	}
	fprintf(out, "\n/* colour formats (pan_format.c, pan_prepare_rt, panfrost_emit_blend, panfrost_new_texture) */\n"
	    "static const struct hm_format hm_formats[4] = {\n");
	for (const char **name = (const char *[]){ "RGBA8Unorm", "BGRA8Unorm", "R8Unorm", "RG8Unorm", NULL }; *name; name++) {
		struct hm_format f;
		if (hm_compile_format(*name, &f) != 0) {
			fprintf(stderr, "bishaders: no format %s\n", *name);
			return 1;
		}
		fprintf(out, "\t{ \"%s\", %u, %u, 0x%03x, 0x%08x, 0x%08x },\n", f.name, f.rt_internal, f.rt_writeback,
		    f.rt_swizzle, f.blend_memory_format, f.texture_format);
	}
	fprintf(out, "};\n");
	fprintf(out, "\n/* textures: RGBA8Unorm's format word and the identity swizzle */\n"
	    "static const uint32_t hm_texture_format_rgba8 = 0x%08x;\nstatic const uint32_t hm_texture_swizzle_identity = 0x%03x;\n",
	    hm_compile_texture_format_rgba8(), hm_compile_swizzle_identity());
	fclose(out);
	printf("bishaders: programs -> %s\n", path);
	return 0;
}
